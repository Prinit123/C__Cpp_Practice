// 1. Classes
// A Class is a user-defined data type. It acts as a blueprint for creating objects. it defines the data (variables) and the behaviors (functions) that the objects will have.

// 2. Objects
// An Object is an instance of a class. When a class is defined, no memory is allocated; memory is only allocated when an object is created.


// 3. The Four Pillars of OOP
// These are the fundamental principles that govern how classes and objects interact.

// I. Encapsulation
// Encapsulation is the process of wrapping data and the functions that manipulate that data into a single unit (the class). It also involves Data Hiding using access specifiers:

// Private: Data cannot be accessed directly from outside the class.

// Public: Data/Functions can be accessed by any part of the program.

// II. Abstraction
// Abstraction means showing only the essential features of an object and hiding the complex internal details. In C++, we often use Header files or Abstract Classes (classes with at least one pure virtual function) to achieve this.

// III. Inheritance
// Inheritance allows a new class (Derived/Child class) to inherit the properties and behaviors of an existing class (Base/Parent class). This promotes code reusability.

// Example: A SportsCar class inherits from a Vehicle class.

// IV. Polymorphism
// As you explored earlier, Polymorphism ("many forms") allows functions to behave differently based on the object they are acting upon.

// Compile-time: Function and Operator Overloading.

// Runtime: Virtual functions and Overriding.



// Concept          Key Definition                  Primary Benefit
// Class            Blueprint / Template            Structure
// Object           Specific Instance               Implementation
// Encapsulation    Data + Methods in one unit      Security / Data Hiding
// Abstraction      Hiding background details       Reduced Complexity
// Inheritance      Deriving new classes            Reusability
// Polymorphism     "One interface, many forms"     Flexibility